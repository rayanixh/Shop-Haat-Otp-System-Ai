<?php
/**
 * Router for the PHP built-in server used during local testing only.
 * Apache/LiteSpeed on cPanel uses .htaccess instead; this file is harmless there.
 */
$path = parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?? '/';
$file = __DIR__ . $path;

// Match the production .htaccess rule for include-only implementation files.
if ($path === '/admin.php' || preg_match('~^/(?:config|includes|ai)/~i', $path) === 1) {
    http_response_code(404);
    echo 'Not found.';
    return true;
}

if ($path !== '/' && is_file($file)) {
    if (substr($file, -4) === '.php') { return false; }
    $mimes = [
        'css' => 'text/css', 'js' => 'application/javascript', 'svg' => 'image/svg+xml',
        'png' => 'image/png', 'jpg' => 'image/jpeg', 'jpeg' => 'image/jpeg',
        'webp' => 'image/webp', 'gif' => 'image/gif', 'ico' => 'image/x-icon',
        'json' => 'application/json', 'txt' => 'text/plain', 'woff2' => 'font/woff2',
    ];
    $ext = strtolower(pathinfo($file, PATHINFO_EXTENSION));
    if (isset($mimes[$ext])) { header('Content-Type: ' . $mimes[$ext]); }
    readfile($file);
    return true;
}
// Mirror the production rewrite rules (.htaccess): the sitemap and robots.txt
// are generated by PHP, so a request for the .xml/.txt URL must reach those
// scripts instead of falling through to the homepage.
if ($path === '/robots.txt' || $path === '/sitemap.xml' || preg_match('~^/sitemap-[0-9]+\.xml$~', $path) === 1) {
    $script = $path === '/robots.txt' ? '/robots.php' : '/sitemap.php';
    $_SERVER['SCRIPT_NAME'] = $script;
    if (preg_match('~^/sitemap-([0-9]+)\.xml$~', $path, $m) === 1) {
        $_GET['file'] = $m[1];
        $_REQUEST['file'] = $m[1];
    }
    require __DIR__ . $script;
    return true;
}

// Custom Admin Access mirrors the root .htaccess one-segment rewrite. The
// dispatcher itself verifies that the route is currently configured. Uppercase
// input is accepted here and normalized to lowercase before comparison.
$reserved = 'admin|adminphp|admin-login|admin-login-php|administrator|wp-admin|cpanel|webmail|login|logout|api|assets|uploads|install|support|cart|checkout|account|orders|products|product|category|categories|robots|sitemap|health|status|security|cron|config|includes|lib|logs|tests|tools|docs|auth|installer|index|track|help|page|payment|password|otp|register';
if (preg_match('~^/(?!(?:' . $reserved . ')(?:/|$))[A-Za-z0-9_-]{3,80}/?$~i', $path) === 1) {
    $_SERVER['SCRIPT_NAME'] = '/admin/custom-route.php';
    require __DIR__ . '/admin/custom-route.php';
    return true;
}

// Guide endpoints (/admin/guides/smtp and /admin/guides/firebase) mirror .htaccess
if (preg_match('~^/admin/guides/(smtp|firebase)/?$~', $path, $m) === 1) {
    $script = '/admin/guides/' . $m[1] . '.php';
    $_SERVER['SCRIPT_NAME'] = $script;
    require __DIR__ . $script;
    return true;
}

if ($path !== '/' && is_dir($file) && is_file(rtrim($file, '/') . '/index.php')) {
    $_SERVER['SCRIPT_NAME'] = rtrim($path, '/') . '/index.php';
    require rtrim($file, '/') . '/index.php';
    return true;
}
$_SERVER['SCRIPT_NAME'] = '/index.php';
require __DIR__ . '/index.php';
